    public void SetLanguage(string langCode)
    {
        var clean = langCode?.Trim();
        if (string.IsNullOrWhiteSpace(clean) || clean.Equals("auto", StringComparison.OrdinalIgnoreCase))
        {
            var systemCulture = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
            _currentLanguage = systemCulture == "nl" ? "nl" : "en";
        }
        else
        {
            _currentLanguage = clean.ToLowerInvariant().StartsWith("nl") ? "nl" : "en";
        }

        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        LanguageChanged?.Invoke();
    }

    internal IReadOnlyCollection<string> GetKeysForLanguage(string langCode)
    {
        var key = langCode?.Trim().ToLowerInvariant() == "nl" ? "nl" : "en";
        return _translations.TryGetValue(key, out var dict) ? dict.Keys.ToList() : Array.Empty<string>();
    }

    public string Get(string key, params object[] args)
    {
        if (string.IsNullOrWhiteSpace(key)) return string.Empty;

        var lang = _currentLanguage;
        if (_translations.TryGetValue(lang, out var dict) && dict.TryGetValue(key, out var text))
        {
            return FormatSafe(text, args);
        }

        // Fallback to English
        if (_translations.TryGetValue("en", out var enDict) && enDict.TryGetValue(key, out var enText))
        {
            return FormatSafe(enText, args);
        }

        return key;
    }

    private static string FormatSafe(string text, object[] args)
    {
        if (args == null || args.Length == 0) return text;
        try
        {
            return string.Format(text, args);
        }
        catch (FormatException)
        {
            return text;
        }
    }
